use std::collections::{BTreeSet, HashMap};
use std::process::ExitCode;

use typesep_style::schema::{Knob, knobs};
use typesep_typst::preamble::{EMITTERS, Emitter, emitter_for, need_matches};

use crate::write_out;

fn group_of(path: &str) -> &str {
    path.split('.').next().unwrap_or(path)
}

fn title_for(group: &str) -> &str {
    match group {
        "page" => "Page",
        "typography" => "Typography",
        "fonts" => "Fonts",
        "headings" => "Headings",
        "blocks" => "Blocks",
        "pageFurniture" => "Headers and footers",
        "toc" => "Table of contents",
        "links" => "Links",
        "notes" => "Notes",
        "cover" => "Cover",
        "output" => "Output",
        "advanced" => "Advanced",
        other => other,
    }
}

#[derive(Default)]
struct Usage {
    count: usize,
    entries: BTreeSet<&'static str>,
}

fn prose(items: &[String]) -> String {
    match items {
        [] => String::new(),
        [one] => one.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    }
}

fn escape_cell(text: &str) -> String {
    text.replace('|', "\\|")
}

pub fn markdown() -> String {
    let mut groups: Vec<&'static str> = Vec::new();
    let mut by_group: HashMap<&'static str, Vec<&'static Knob>> = HashMap::new();
    for knob in knobs() {
        let group = group_of(&knob.path);
        if !by_group.contains_key(group) {
            groups.push(group);
        }
        by_group.entry(group).or_default().push(knob);
    }

    let mut usage: HashMap<&'static str, HashMap<&'static str, Usage>> = HashMap::new();
    for knob in knobs() {
        let group = group_of(&knob.path);
        for emitter in emitter_for(&knob.path) {
            let info = usage
                .entry(emitter.name)
                .or_default()
                .entry(group)
                .or_default();
            info.count += 1;
            if let Some(matched) = emitter.needs.iter().find(|n| need_matches(n, &knob.path)) {
                info.entries.insert(matched);
            }
        }
    }

    let primary_group = |emitter: &Emitter| -> &'static str {
        let per_group = &usage[emitter.name];
        let mut best = group_of(emitter.needs[0]);
        let mut best_count = per_group.get(best).map_or(0, |u| u.count);
        for (group, info) in per_group {
            if info.count > best_count {
                best = group;
                best_count = info.count;
            }
        }
        best
    };

    let mut out: Vec<String> = vec![
        "# Style reference".to_owned(),
        String::new(),
        "Every option below can be set in a preset, in a style file, or on the command".to_owned(),
        "line with `-s path=value`. Layers merge in that order, with `-s` winning. A style"
            .to_owned(),
        "file may begin with `preset: <name>` (or `none`) to say which preset it builds on;"
            .to_owned(),
        "`--preset` on the command line overrides it.".to_owned(),
        String::new(),
        "Each section ends with the Typst that implements its options. That matters when"
            .to_owned(),
        "you add your own code through `advanced.preamble`, or when a Typst error names a"
            .to_owned(),
        "construct and you need the option behind it. `typesep explain <path>` shows the"
            .to_owned(),
        "same mapping for a single option.".to_owned(),
        String::new(),
        "This file is generated by `make docs`. Edit the option table in".to_owned(),
        "`crates/sep-core/src/style/schema.rs` and the Typst notes in".to_owned(),
        "`crates/sep-typst/src/preamble.rs`.".to_owned(),
        String::new(),
    ];

    for group in groups {
        out.push(format!("## {}", title_for(group)));
        out.push(String::new());
        out.push("| option | accepts | default | what it does |".to_owned());
        out.push("| --- | --- | --- | --- |".to_owned());
        for knob in &by_group[group] {
            out.push(format!(
                "| `{}` | {} | `{}` | {} |",
                knob.path,
                escape_cell(&knob.kind.describe()),
                knob.default.to_json(),
                escape_cell(&knob.doc)
            ));
        }
        out.push(String::new());

        let mut primary: Vec<String> = Vec::new();
        let mut strays: Vec<(&'static str, Vec<String>)> = Vec::new();
        for emitter in EMITTERS {
            let Some(info) = usage.get(emitter.name).and_then(|per| per.get(group)) else {
                continue;
            };
            let entries: Vec<&'static str> = emitter
                .needs
                .iter()
                .copied()
                .filter(|n| info.entries.contains(n))
                .collect();
            if primary_group(emitter) == group {
                let paths: Vec<String> = entries.iter().map(|n| format!("`{n}`")).collect();
                primary.push(format!(
                    "- **{}** ({}): {}.",
                    emitter.name,
                    emitter.typst,
                    paths.join(", ")
                ));
            } else {
                for need in entries {
                    match strays.iter_mut().find(|(n, _)| *n == need) {
                        Some((_, names)) => names.push(format!("**{}**", emitter.name)),
                        None => strays.push((need, vec![format!("**{}**", emitter.name)])),
                    }
                }
            }
        }
        if !primary.is_empty() || !strays.is_empty() {
            out.push("Under the hood:".to_owned());
            out.push(String::new());
            out.extend(primary);
            for (need, names) in strays {
                out.push(format!("- `{need}` also feeds {}.", prose(&names)));
            }
            out.push(String::new());
        }
    }

    out.join("\n")
}

pub fn write() -> ExitCode {
    write_out(&format!("{}\n", markdown()));
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_knob_has_a_row() {
        let page = markdown();
        for knob in knobs() {
            let row = page
                .lines()
                .find(|line| line.starts_with(&format!("| `{}` |", knob.path)))
                .unwrap_or_else(|| panic!("no row for {}", knob.path));
            assert_eq!(row.matches(" | ").count(), 3, "four cells in {}", knob.path);
            assert!(
                row.contains(&format!("| `{}` |", knob.default.to_json())),
                "the default of {} is missing",
                knob.path
            );
        }
    }

    #[test]
    fn every_emitter_an_option_drives_is_listed_once() {
        let page = markdown();
        for emitter in EMITTERS {
            let full = page
                .lines()
                .filter(|line| line.starts_with(&format!("- **{}** (", emitter.name)))
                .count();
            let wanted = usize::from(!emitter.needs.is_empty());
            assert_eq!(
                full, wanted,
                "{} is described {full} times, wanted {wanted}",
                emitter.name
            );
        }
    }
}
